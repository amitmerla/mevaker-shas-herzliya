// Turns extracted pages (+ docs/text/<id>.txt) into js/corpus.js passages. Removes emails, phone and ID numbers.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { DOCS } from '../js/data.js';

const pages = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const clean = (s) => s
  .replace(/[\w.+-]+@[\w-]+(\.[\w-]+)+/g, '[דוא"ל הושמט]')
  .replace(/(?<!\d)0\d{1,2}[-\s]?\d{7}(?!\d)/g, '[טלפון הושמט]')
  .replace(/(?<!\d)\d{9}(?!\d)/g, (m) => (/^(5|0)/.test(m) ? m : '[מספר הושמט]'))
  .replace(/\s+/g, ' ').trim();

function chunks(text, size = 650, overlap = 120) {
  const out = []; let i = 0;
  while (i < text.length) {
    let end = Math.min(text.length, i + size);
    if (end < text.length) { const sp = text.lastIndexOf(' ', end); if (sp > i + size * .6) end = sp; }
    out.push(text.slice(i, end).trim());
    if (end >= text.length) break;
    i = Math.max(end - overlap, i + 1);
    const sp = text.indexOf(' ', i); if (sp > 0 && sp < end) i = sp + 1;
  }
  return out.filter((c) => c.length > 30);
}

const out = [], report = [];
for (const d of DOCS) {
  const manual = `docs/text/${d.id}.txt`;
  let ps = [];
  if (existsSync(manual)) {
    ps = readFileSync(manual, 'utf8').split(/^--- עמ׳ (\d+) ---$/m).slice(1)
      .reduce((a, x, i, arr) => (i % 2 ? a : [...a, { page: +x, text: arr[i + 1] || '' }]), []);
  } else {
    ps = pages.filter((p) => p.id === d.id);
  }
  let n = 0;
  for (const p of ps) for (const c of chunks(clean(p.text))) { out.push([d.id, p.page, c]); n++; }
  report.push(`${n ? '✓' : '✗'} ${d.id.padEnd(9)} ${String(n).padStart(3)} passages${existsSync(manual) ? ' (docs/text)' : ''}${n ? '' : '  ← no text: add docs/text/' + d.id + '.txt'}`);
}
writeFileSync('js/corpus.js', `// Generated by tools/build-corpus.sh — do not edit by hand. [doc id, page, passage]\nexport const CORPUS = ${JSON.stringify(out)};\n`);
console.log(report.join('\n'));
console.log(`\n${out.length} passages from ${DOCS.length} documents → js/corpus.js (${Math.round(readFileSync('js/corpus.js').length / 1024)} KB)`);
